package main

import (
	"cmp"
	"fmt"
	"path/filepath"
	"slices"
	"strings"
)

// renderer builds the Markdown document.
type renderer struct {
	out       strings.Builder
	inventory *Inventory
}

// Render writes the inventory as Markdown. The output depends only on the
// trees, their commits and the tool, so two runs are byte-identical.
func (inventory *Inventory) Render() []byte {
	view := &renderer{inventory: inventory}
	view.header()
	view.summary()
	view.referencedNames()
	view.methodSets()
	view.callSites()
	view.mapSites()
	view.errorAndRenderingSites()
	view.boundaries()
	return []byte(view.out.String())
}

func (view *renderer) line(format string, arguments ...any) {
	fmt.Fprintf(&view.out, format+"\n", arguments...)
}

// cell escapes text for a Markdown table cell.
func cell(text string) string {
	text = strings.ReplaceAll(text, "|", "\\|")
	return strings.ReplaceAll(text, "\n", " ")
}

func (view *renderer) row(cells ...string) {
	escaped := make([]string, len(cells))
	for index, text := range cells {
		escaped[index] = cell(text)
	}
	view.line("| %s |", strings.Join(escaped, " | "))
}

func (view *renderer) tableHead(columns ...string) {
	view.row(columns...)
	separators := make([]string, len(columns))
	for index := range separators {
		separators[index] = "---"
	}
	view.line("| %s |", strings.Join(separators, " | "))
}

func (view *renderer) labels() []string {
	labels := make([]string, len(view.inventory.Config.Trees))
	for index, tree := range view.inventory.Config.Trees {
		labels[index] = tree.Label
	}
	return labels
}

func (view *renderer) header() {
	view.line("# API inventory")
	view.line("")
	view.line("Generated by `tools/inventory` from type-checked source (`go/packages` and `go/types`), as spec 5.1 requires.")
	view.line("Do not edit by hand: regenerate with the command at the end of this section.")
	view.line("")
	view.tableHead("Input", "Directory", "Commit", "Vendor module version")
	view.row("tool", "tools/inventory", view.inventory.Config.ToolCommit, "")
	for _, tree := range view.inventory.Config.Trees {
		view.row(tree.Label+" tree", filepath.Base(tree.Dir), tree.Commit, view.inventory.VendorVersions[tree.Label])
	}
	view.line("")
	view.line("Regenerate (the toolchain must be the server's `go` directive or newer, so the type checker reads its standard library):")
	view.line("")
	view.line("    cd tools/inventory && GOTOOLCHAIN=go<server go version> go run . \\")
	view.line("      -tool-commit <this tool's commit> -server <hoardDB dir> -server-commit <hash> \\")
	view.line("      -driver <hoarddb-go dir> -driver-commit <hash> -o ../../docs/api-inventory.md")
	view.line("")
	view.line("What the tool cannot see: a target whose static type is `interface{}`, a non-empty interface or a type parameter is")
	view.line("marked `pending tap` and completed by the runtime tap (spec 9.1.7, build step 6a). An error that reaches a print, compare")
	view.line("or branch only after being returned through other functions is not followed: section 5 lists the places where an error")
	view.line("variable that received a vendor call's error is used, plus every use of a vendor error type or sentinel. The tool does")
	view.line("not attempt per-site quirk notes (spec 5.1 item 3).")
	view.line("")
	view.line("Which assignment reaches an error use is decided by source order and nesting, not by control flow. A use counts as a codec")
	view.line("error use when the nearest preceding assignment in a block that also holds the use, or any nearer assignment in a block that")
	view.line("does not, is a vendor codec call. So a reassignment on every branch of an `if` still leaves the use labelled (an extra row),")
	view.line("and an assignment that comes later in a loop body than the use is not followed (a missing row).")
	view.line("")
}

func (view *renderer) summary() {
	inventory := view.inventory
	pending := 0
	for _, call := range inventory.Calls {
		if call.PendingTap {
			pending++
		}
	}
	totalRefs := 0
	for _, reference := range inventory.References {
		for _, count := range reference.Counts {
			totalRefs += count
		}
	}
	view.line("## Summary")
	view.line("")
	view.tableHead("Measure", "Count")
	for _, label := range view.labels() {
		view.row("files importing a vendor path, "+label+" tree", fmt.Sprint(inventory.ImportingFiles[label]))
	}
	view.row("exported vendor names referenced", fmt.Sprint(len(inventory.References)))
	view.row("references to them", fmt.Sprint(totalRefs))
	view.row("vendor types listed with their whole method set", fmt.Sprint(len(inventory.Types)))
	view.row("marshal, unmarshal and Extended JSON call sites", fmt.Sprint(len(inventory.Calls)))
	view.row("call sites whose class is `pending tap`", fmt.Sprint(pending))
	definiteMaps := 0
	for _, site := range inventory.MapSites {
		if !site.Pending {
			definiteMaps++
		}
	}
	view.row("marshal sites whose target is or contains a map", fmt.Sprint(definiteMaps))
	view.row("marshal sites whose target may hold a map (pending tap)", fmt.Sprint(len(inventory.MapSites)-definiteMaps))
	view.row("error-text and error-identity sites", fmt.Sprint(len(inventory.ErrorSites)))
	view.row("string-rendering sites", fmt.Sprint(len(inventory.Renderings)))
	view.row("boundary functions configured", fmt.Sprint(len(inventory.Boundaries)))
	view.row("distinct enclosing functions of boundary calls, non-test", fmt.Sprint(len(view.boundaryCallerSet(false))))
	view.line("")
}

func (view *renderer) siteText(site Site) string {
	return fmt.Sprintf("%s:%s:%d:%d", site.Tree, site.File, site.Line, site.col)
}

func (view *renderer) referencedNames() {
	inventory := view.inventory
	view.line("## 1. Referenced names")
	view.line("")
	view.line("Every exported name from the vendor packages that a tree references, with reference counts. Counts are identifier")
	view.line("uses resolved by the type checker, one per source occurrence; a file compiled into several test variants counts once.")
	view.line("")
	view.line("### Import paths")
	view.line("")
	columns := []string{"Vendor import path", "Library path"}
	for _, label := range view.labels() {
		columns = append(columns, "files, "+label, "type-checked, "+label)
	}
	view.tableHead(columns...)
	for _, importCount := range inventory.Imports {
		cells := []string{importCount.Path, importCount.Mirror}
		for _, label := range view.labels() {
			cells = append(cells, fmt.Sprint(importCount.Files[label]), fmt.Sprint(importCount.Loaded[label]))
		}
		view.row(cells...)
	}
	view.line("")
	view.line("`files` counts every `.go` file under the tree whose imports name the path, built or not (the `grep -rl` count).")
	view.line("`type-checked` counts files the loader built with tests. They differ for build-tagged files and nested modules.")
	if len(inventory.NotLoaded) > 0 {
		view.line("")
		view.line("Files that import a mirrored path but were not type-checked (%d), so their references are not in this inventory:", len(inventory.NotLoaded))
		view.line("")
		for _, path := range inventory.NotLoaded {
			view.line("- `%s`", path)
		}
	}
	view.line("")
	view.line("### Names")
	view.line("")
	columns = []string{"Name", "Kind"}
	columns = append(columns, view.labels()...)
	columns = append(columns, "Total")
	view.tableHead(columns...)
	for _, reference := range inventory.References {
		cells := []string{"`" + reference.Name + "`", reference.Kind}
		total := 0
		for _, label := range view.labels() {
			cells = append(cells, fmt.Sprint(reference.Counts[label]))
			total += reference.Counts[label]
		}
		view.row(append(cells, fmt.Sprint(total))...)
	}
	view.line("")
}

func (view *renderer) methodSets() {
	view.line("## 2. Whole method sets")
	view.line("")
	view.line("A type is listed when a tree names it or any expression in the tree has it (or holds it in a slice, array, map, pointer")
	view.line("or result). It is mirrored whole: interface satisfaction is invisible to references (`fmt` calls `String`, `encoding/json`")
	view.line("calls `MarshalJSON`, the codec calls `IsZero`). `implicit` lists the methods of that kind.")
	view.line("")
	for _, entry := range view.inventory.Types {
		reached := ""
		if entry.NameRefs == 0 {
			reached = ", reached only through expressions (no reference by name)"
		}
		view.line("### `%s`", entry.Name)
		view.line("")
		view.line("%s; %d references by name%s.", entry.Kind, entry.NameRefs, reached)
		if len(entry.Aliases) > 0 {
			view.line("Also spelled: `%s`.", strings.Join(entry.Aliases, "`, `"))
		}
		if len(entry.Implicit) > 0 {
			view.line("Implicit: `%s`.", strings.Join(entry.Implicit, "`, `"))
		}
		view.fieldLines(entry)
		view.line("")
		view.line("Methods (%d):", len(entry.Methods))
		view.line("")
		for _, signature := range entry.Signatures {
			view.line("- `%s`", signature)
		}
		view.line("")
	}
}

func (view *renderer) fieldLines(entry TypeEntry) {
	if len(entry.Fields) > 0 {
		pairs := make([]string, len(entry.Fields))
		for index, name := range entry.Fields {
			pairs[index] = name + " " + entry.FieldTypes[index]
		}
		view.line("")
		view.line("Exported fields: `%s`.", strings.Join(pairs, "`, `"))
	}
	if len(entry.UnexportedFields) > 0 {
		view.line("")
		view.line("Unexported fields (not mirrorable by name, kept in mind for zero values and copies): `%s`.", strings.Join(entry.UnexportedFields, "`, `"))
	}
}

func (view *renderer) callSites() {
	inventory := view.inventory
	view.line("## 3. Marshal and unmarshal call sites")
	view.line("")
	view.line("Every `Marshal`, `Unmarshal`, `MarshalValue`, `RawValue.Unmarshal`, Extended JSON and `Encoder`/`Decoder` call, with the")
	view.line("static class of its target. `pending tap` marks a target the static type does not decide.")
	view.line("")
	classCounts := map[[3]string]int{}
	for _, call := range inventory.Calls {
		pending := ""
		if call.PendingTap {
			pending = "pending tap"
		}
		classCounts[[3]string{call.Kind, call.Class, pending}]++
	}
	keys := make([][3]string, 0, len(classCounts))
	for key := range classCounts {
		keys = append(keys, key)
	}
	slices.SortFunc(keys, func(left, right [3]string) int {
		return cmp.Or(cmp.Compare(left[0], right[0]), cmp.Compare(left[1], right[1]))
	})
	view.line("### By kind and class")
	view.line("")
	view.tableHead("Kind", "Class", "Status", "Sites")
	for _, key := range keys {
		view.row(key[0], key[1], key[2], fmt.Sprint(classCounts[key]))
	}
	view.line("")
	view.line("### Sites")
	view.line("")
	view.tableHead("Site", "In", "Call", "Kind", "Static target type", "Class", "Status", "Note")
	for _, call := range inventory.Calls {
		status := ""
		if call.PendingTap {
			status = "pending tap"
		}
		view.row(view.siteText(call.Site), call.Func, call.Callee, call.Kind, call.TargetType, call.Class, status, call.Note)
	}
	view.line("")
}

func (view *renderer) mapSites() {
	view.line("## 4. Map-marshal sites")
	view.line("")
	view.line("Marshal calls whose static target is a map, or a struct that reaches a map through an exported field. The vendor encodes")
	view.line("a map in random key order, so these are the sites whose bytes are not reproducible (spec 6.1). A target typed as an")
	view.line("interface is listed as \"may hold a map (pending tap)\": the static type cannot tell, and the runtime tap decides.")
	view.line("")
	view.tableHead("Site", "In", "Call", "Target", "Map reached")
	for _, site := range view.inventory.MapSites {
		view.row(view.siteText(site.Call.Site), site.Call.Func, site.Call.Callee, site.Call.TargetType, site.Via)
	}
	view.line("")
}

func (view *renderer) errorAndRenderingSites() {
	inventory := view.inventory
	view.line("## 5. Error-text and rendering sites")
	view.line("")
	view.line("### Codec and Extended JSON errors")
	view.line("")
	view.line("Uses of an error variable that received a vendor call's error, of a value of a vendor error type, or of an exported vendor")
	view.line("error variable, that print, wrap, truncate, compare or branch. Uses that only return the error or test it against `nil`")
	view.line("are not listed. `errors.Is` is listed as a comparison; `errors.As` matches by type and is not listed.")
	view.line("")
	actionCounts := map[string]int{}
	for _, site := range inventory.ErrorSites {
		actionCounts[site.Action]++
	}
	view.tableHead("Action", "Sites")
	for _, action := range sortedKeys(actionCounts) {
		view.row(action, fmt.Sprint(actionCounts[action]))
	}
	view.line("")
	view.tableHead("Site", "In", "Action", "Error came from")
	for _, site := range inventory.ErrorSites {
		view.row(view.siteText(site.Site), site.Func, site.Action, site.Origin)
	}
	view.line("")
	view.line("### String renderings")
	view.line("")
	view.line("`explicit` is a call to a vendor `Hex`, `String` or `GoString`. `implicit fmt` is a vendor value with a `String` method passed to")
	view.line("`fmt` or `log`. `implicit json` is a vendor value reached by `encoding/json`, which renders it through `MarshalJSON`. `json tag` is a struct field")
	view.line("with a `json` tag that holds such a value: the struct reaches `encoding/json` wherever it is marshalled, even through an `interface{}`.")
	view.line("")
	formCounts := map[string]int{}
	for _, site := range inventory.Renderings {
		formCounts[site.Form]++
	}
	view.tableHead("Form", "Sites")
	for _, form := range sortedKeys(formCounts) {
		view.row(form, fmt.Sprint(formCounts[form]))
	}
	view.line("")
	view.tableHead("Site", "In", "Form", "Name", "Reached through")
	for _, site := range inventory.Renderings {
		view.row(view.siteText(site.Site), site.Func, site.Form, site.Name, site.Detail)
	}
	view.line("")
}

func sortedKeys(counts map[string]int) []string {
	keys := make([]string, 0, len(counts))
	for key := range counts {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}

// boundaryCallerSet returns the distinct enclosing functions of boundary calls.
func (view *renderer) boundaryCallerSet(includeTests bool) map[string]bool {
	functions := map[string]bool{}
	for _, entry := range view.inventory.Boundaries {
		for _, caller := range entry.Callers {
			if caller.Test && !includeTests {
				continue
			}
			functions[caller.Tree+":"+caller.File+":"+caller.Func] = true
		}
	}
	return functions
}

func (view *renderer) boundaries() {
	view.line("## 6. Boundary functions")
	view.line("")
	view.line("The enclosing function of every call to a configured boundary function (build step 7b). A function that appears for")
	view.line("several boundaries is one function. `Calls` counts the call expressions inside it. A boundary with no definition is listed")
	view.line("so that a rename is visible.")
	view.line("")
	view.line("Distinct enclosing functions: %d outside tests, %d with tests.", len(view.boundaryCallerSet(false)), len(view.boundaryCallerSet(true)))
	view.line("")
	for _, entry := range view.inventory.Boundaries {
		view.line("### `%s`", entry.Name)
		view.line("")
		if len(entry.Defined) == 0 {
			view.line("Defined: not found in the inventoried trees.")
		} else {
			view.line("Defined: `%s`.", strings.Join(entry.Defined, "`, `"))
		}
		view.line("")
		if len(entry.Callers) == 0 {
			view.line("No callers.")
			view.line("")
			continue
		}
		view.tableHead("Enclosing function", "File", "Calls", "Test")
		for _, caller := range entry.Callers {
			test := ""
			if caller.Test {
				test = "test"
			}
			view.row(caller.Func, caller.Tree+":"+caller.File, fmt.Sprint(caller.Calls), test)
		}
		view.line("")
	}
}
